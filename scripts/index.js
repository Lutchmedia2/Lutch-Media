function vlayout() {
  vels.forEach((e, i) => {
    const o = i - va,
      ao = Math.abs(o),
      w = e.offsetWidth;
    e.style.transform =
      "translate(-50%,-50%) translate(" +
      o * w * 0.78 +
      "px," +
      ao * ao * w * 0.035 +
      "px) rotate(" +
      o * 7 +
      "deg) scale(" +
      (1 - Math.min(ao, 3) * 0.05) +
      ")";
    e.style.zIndex = 10 - ao;
    e.style.opacity = ao > 3 ? 0 : 1;
    e.style.pointerEvents = ao > 3 ? "none" : "auto";
    e.style.filter = ao ? "brightness(" + (0.62 - Math.min(ao, 3) * 0.06) + ")" : "none";
    e.classList.toggle("on", !ao);
  });
  [...vdots.children].forEach((d, i) => d.setAttribute("aria-current", i === va));
}
